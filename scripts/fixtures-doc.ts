/**
 * Writes docs/m2/CALCULATOR-FIXTURES.md from the code and the tests, so the
 * list offered for review by a qualified pharmacist is the list that is
 * actually tested: per calculator, its citation, its inputs with their
 * plausibility ranges and definitional limits, and every test case with the
 * origin of its values (named in the test title); then the allergy class
 * words and the causality scoring tables.
 *
 *   npx vitest run tests/calc --reporter=json --outputFile=<report.json>
 *   npx vite-node scripts/fixtures-doc.ts <report.json>
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { CALCULATOR_DEFS } from '../src/calc/registry';
import type { CalculatorDef, InputSpec } from '../src/calc/types';
import { QUANTITIES, type QuantityId } from '../src/calc/units';
import { ALLERGY_CLASS_TERMS } from '../src/rules/allergy-terms';
import { NARANJO_CITATION, NARANJO_QUESTIONS, UMC_CITATION, UMC_QUESTIONS } from '../src/rules/causality';
import manifest from '../src/calc/validation-manifest.json';

const ROOT = process.cwd();
const OUT = 'docs/m2/CALCULATOR-FIXTURES.md';

/** Test titles per calculator id, from a test run's JSON report (every `it.each` row expanded), with their result. */
function testTitles(reportPath: string): Map<string, { title: string; status: string }[]> {
  const report = JSON.parse(readFileSync(reportPath, 'utf8')) as {
    testResults: { name: string; assertionResults: { ancestorTitles: string[]; title: string; status: string }[] }[];
  };
  const out = new Map<string, { title: string; status: string }[]>();
  for (const file of [...report.testResults].sort((a, b) => (a.name < b.name ? -1 : 1))) {
    for (const t of file.assertionResults) {
      const m = /^calc:([a-z0-9_]+)@/.exec(t.ancestorTitles[0] ?? '');
      if (!m) continue;
      out.set(m[1]!, [...(out.get(m[1]!) ?? []), { title: t.title, status: t.status }]);
    }
  }
  return out;
}

function unitOf(s: InputSpec): string {
  if (s.kind in QUANTITIES) return QUANTITIES[s.kind as QuantityId].canonical;
  if (s.kind === 'age') return 'years';
  return '';
}

const range = (r?: readonly [number, number]) => (r ? `${r[0]} – ${r[1]}` : '—');
const esc = (s: string) => s.replace(/\|/g, '\\|');

function inputRows(def: CalculatorDef): string[] {
  const rows = [
    '| Input | Required | Unit (canonical) | Plausible range (confirmation outside) | Definitional limits (rejected outside) |',
    '|---|---|---|---|---|',
  ];
  for (const [list, req] of [
    [def.requiredInputs, 'yes'],
    [def.optionalInputs, 'optional'],
  ] as const) {
    for (const s of list) {
      const choice = s.options ? ` (choice: ${s.options.map((o) => o.label.en).join(' / ')})` : '';
      const when = s.showIf ? ` — asked when ${s.showIf.key} is ${s.showIf.in.join(' or ')}` : '';
      rows.push(`| ${esc(s.label.en)}${esc(choice)}${esc(when)} | ${req} | ${unitOf(s) || '—'} | ${range(s.plausible)} | ${range(s.limits)} |`);
    }
  }
  return rows;
}

function main() {
  const report = process.argv[2];
  if (!report) throw new Error('Usage: vite-node scripts/fixtures-doc.ts <vitest JSON report>');
  const titles = testTitles(report);
  const m = manifest as { generatedAt: string; engineTests: { passed: number; failed: number }; calculators: Record<string, { formulaVersion: string; passed: number; failed: number }> };
  const lines: string[] = [];
  lines.push('# PRECEPTOR — M2 calculator fixtures, plausibility ranges and rule tables');
  lines.push('');
  lines.push('*Generated by `scripts/fixtures-doc.ts` from the calculator definitions and a run of their tests (each case below is marked with its result in that run). Do not edit by hand.*');
  lines.push('');
  lines.push('This is the list offered for review by a qualified pharmacist (M2 plan, Section 8). Every test value has a recorded origin, given in the test title:');
  lines.push('');
  lines.push('- **published** — a worked example in a named published source;');
  lines.push('- **hand** — the arithmetic is written out in the title or the test;');
  lines.push('- **independent** — computed by `scripts/calc-crosscheck.py`, a separate Python implementation written from the cited formula (not from the TypeScript code);');
  lines.push('- tests without a number check behaviour: refusals, unit handling, warnings, boundaries.');
  lines.push('');
  lines.push(`Validation manifest: generated ${m.generatedAt}; engine tests passed ${m.engineTests.passed}, failed ${m.engineTests.failed}. A calculator is shown in the app only with a passing record for its exact formula version and an unchanged engine.`);
  lines.push('');
  lines.push('Plausibility ranges are deliberately wide: they catch unit slips and typing errors and are not reference ranges. A value outside one is used only after the trainee confirms it, with the value and unit shown. A value outside the definitional limits is rejected.');
  lines.push('');
  lines.push('## Calculators');
  for (const def of CALCULATOR_DEFS) {
    const rec = m.calculators[def.id];
    lines.push('');
    lines.push(`### ${def.name} — \`${def.id}@${def.formulaVersion}\``);
    lines.push('');
    lines.push(`- Formula: ${def.formula}`);
    lines.push(`- Citation: ${def.citation}`);
    lines.push(`- Tests: ${rec ? `${rec.passed} passed, ${rec.failed} failed (formula version ${rec.formulaVersion})` : 'no record'}${def.highRisk ? ' · high-risk calculation: extended tests and an escalation message' : ''}`);
    if (def.limitations.length) lines.push(`- Limitations shown with every result: ${def.limitations.map((l) => l.en).join(' ')}`);
    lines.push('');
    lines.push(...inputRows(def));
    lines.push('');
    lines.push('Test cases:');
    lines.push('');
    for (const t of titles.get(def.id) ?? []) lines.push(`1. ${t.status === 'passed' ? '✓' : `✗ (${t.status})`} ${t.title}`);
  }

  lines.push('');
  lines.push('## Allergy class words');
  lines.push('');
  lines.push('An allergy record that names a class ("penicillin allergy", "sulfa", "NSAIDs") is matched to these FDA Established Pharmacologic Classes (ids as published in RxClass). A word that is also an ingredient name in the singular ("tetracycline", "heparin") is matched as the ingredient; only its plural names the class. This is vocabulary, not clinical judgement; the class names below are read from the installed RxNorm subset.');
  lines.push('');
  const subset = JSON.parse(readFileSync(join(ROOT, 'public/data/rxnorm-subset.json'), 'utf8')) as { epc: [string, string, string[]][] };
  const className = new Map(subset.epc.map(([id, name, members]) => [id, `${name} (${members.length} ingredient${members.length === 1 ? '' : 's'})`]));
  const byClasses = new Map<string, string[]>();
  for (const [word, ids] of Object.entries(ALLERGY_CLASS_TERMS)) {
    const k = ids.join(',');
    byClasses.set(k, [...(byClasses.get(k) ?? []), word]);
  }
  lines.push('| Words in the allergy record | FDA EPC classes |');
  lines.push('|---|---|');
  for (const [ids, words] of byClasses) lines.push(`| ${words.map((w) => `“${w}”`).join(', ')} | ${ids.split(',').map((id) => `${className.get(id) ?? 'not in the installed subset'} — ${id}`).join('; ')} |`);

  lines.push('');
  lines.push('## Naranjo scoring table');
  lines.push('');
  lines.push(`Source: ${NARANJO_CITATION} Total ≥ 9 definite, 5–8 probable, 1–4 possible, ≤ 0 doubtful.`);
  lines.push('');
  lines.push('| # | Question | Yes | No | Do not know |');
  lines.push('|---|---|---|---|---|');
  NARANJO_QUESTIONS.forEach((q, i) => lines.push(`| ${i + 1} | ${esc(q.label.en)} | ${q.points.yes} | ${q.points.no} | ${q.points.unknown} |`));

  lines.push('');
  lines.push('## WHO-UMC criteria');
  lines.push('');
  lines.push(`Source: ${UMC_CITATION} The category follows from the answers by fixed rules (src/rules/causality.ts, \`assessUmc\`), tried from the strongest category to the weakest.`);
  lines.push('');
  for (const q of UMC_QUESTIONS) lines.push(`- ${q.label.en} — ${q.options.map((o) => o.label.en).join(' / ')}`);
  lines.push('');
  writeFileSync(join(ROOT, OUT), `${lines.join('\n')}`);
  console.log(`wrote ${OUT}`);
}

main();

/**
 * Writes docs/m4/PCNE-MAPPINGS.md from the code, so the tables offered to the
 * owner for approval are the tables the app uses: every PCNE V9.1 problem
 * and cause code with its official wording, the department form box and the
 * Cipolle category it maps to, the reason where the choice is a judgement,
 * the rules that combine several codes, and worked examples computed by the
 * same functions.
 *
 *   npx vite-node scripts/pcne-doc.ts
 */
import { writeFileSync } from 'node:fs';
import { PCNE_CAUSES, PCNE_CITATION, PCNE_CODE, PCNE_DOMAIN, PCNE_PROBLEMS, PCNE_TERMS, type PcneCode } from '../src/domain/pcne';
import {
  CIPOLLE_CATEGORIES,
  CIPOLLE_CITATION,
  CIPOLLE_NOT_EQUIVALENT,
  PCNE_MAPS_APPROVAL,
  PCNE_MAPS_APPROVED,
  PCNE_TO_CIPOLLE,
  PCNE_TO_FORM_BOX,
  cipolleFor,
  formBoxesFor,
  mapsFingerprint,
  type CipolleRuleTo,
} from '../src/domain/pcne-maps';
import { DRP_CATEGORIES } from '../src/domain/workflow/registers';

const OUT = 'docs/m4/PCNE-MAPPINGS.md';

const boxLabel = (id: string) => (id === 'problem' ? '*the problem’s box*' : DRP_CATEGORIES.find((c) => c.value === id)!.label.en);
const cipLabel = (id: string) => (id === 'none' ? '*no equivalent*' : id === 'problem' ? '*the problem’s category*' : CIPOLLE_CATEGORIES.find((c) => c.id === id)!.label.en);
const cipTo = (to: CipolleRuleTo) => (typeof to === 'string' ? cipLabel(to) : `P1: ${cipLabel(to.P1)}; P2: ${cipLabel(to.P2)}; P3: ${cipLabel(to.P3)}`);
const esc = (s: string) => s.replace(/\|/g, '\\|');

function rows(codes: readonly PcneCode[]): string[] {
  const out: string[] = [];
  let domain = '';
  for (const x of codes) {
    if (x.domain !== domain) {
      domain = x.domain;
      out.push(`| **${domain}** | **${PCNE_DOMAIN.get(domain)!.label.en}** | | | |`);
    }
    const box = PCNE_TO_FORM_BOX[x.code]!;
    const cip = PCNE_TO_CIPOLLE[x.code]!;
    const why = [box.why ? `Form: ${box.why}` : '', cip.why ? `Cipolle: ${cip.why}` : ''].filter(Boolean).join(' ');
    out.push(`| ${x.code} | ${esc(x.label.en)} | ${box.decide ? '**⚑** ' : ''}${boxLabel(box.box)} | ${cipTo(cip.to)} | ${esc(why)} |`);
  }
  return out;
}

const EXAMPLES: [string, string[]][] = [
  ['P1.2', ['C3.1']],
  ['P1.2', ['C3.1', 'C8.1']],
  ['P1.2', ['C7.1', 'C3.1']],
  ['P1.1', ['C1.1']],
  ['P2.1', ['C1.1']],
  ['P2.1', ['C3.2']],
  ['P2.1', ['C1.3']],
  ['P1.2', ['C1.3']],
  ['P2.1', ['C9.1']],
  ['P1.3', ['C1.5']],
  ['P3.1', ['C1.2', 'C1.4']],
  ['P3.2', []],
];

const decide = Object.entries(PCNE_TO_FORM_BOX).filter(([, r]) => r.decide);

const approved = PCNE_MAPS_APPROVED && mapsFingerprint() === PCNE_MAPS_APPROVAL.fingerprint;

const lines = [
  `# PCNE V9.1 — the two mappings${approved ? '' : ', for the owner’s review'}`,
  '',
  `*Generated by \`scripts/pcne-doc.ts\` from \`src/domain/pcne.ts\` and \`src/domain/pcne-maps.ts\` (\`npm run docs:pcne\`). Do not edit by hand.*`,
  '',
  approved
    ? `**Status: approved by the owner on 20 October 2026, as they stand, with the nine choices marked ⚑.** Fingerprint of the approved results: \`${PCNE_MAPS_APPROVAL.fingerprint}\` (\`mapsFingerprint()\`). If a table or a rule changes, a unit test fails until the owner approves the change; meanwhile the approval is withdrawn and the screens say “draft” again.`
    : '**Status: DRAFT — waiting for the owner’s approval.** Until approved, every screen that shows a mapped box or category says it is a draft.',
  '',
  '## Source',
  '',
  `- ${PCNE_CITATION}. The codes and their English wording are copied from the official English document (PDF of 7 January 2026) and checked word for word against it; the Arabic lines in the app are PRECEPTOR’s explanations, not a PCNE translation.`,
  `- PCNE’s terms (from the document): “${PCNE_TERMS}”`,
  '- **Action for the department:** PCNE asks to be informed of the classification’s use (drp@pcne.org). PRECEPTOR is non-commercial teaching and practice; the department should send that notice. PRECEPTOR does not contact anyone.',
  `- Cipolle categories: ${CIPOLLE_CITATION} Only the category names are used.`,
  '',
  '## How codes combine',
  '',
  '**Form boxes (Section 15, Section 8).** Each problem and cause code maps to one box. A card ticks the boxes of its causes; the box of its problem is added only when the causes give no box but “other” (or there is no cause). A code whose box is “other” writes its PCNE wording in the form’s free-text field. *Why:* PCNE separates the problem from its cause, and the form’s boxes are mostly causes — “effect not optimal” caused by a low dose should tick “dose too low”, not also “ineffective therapy”. The trainee can adjust the boxes before export.',
  '',
  `**Cipolle (teaching view).** ${CIPOLLE_NOT_EQUIVALENT.en} Each cause gives a category, or none; some depend on the problem’s domain (P1 effectiveness, P2 safety, P3 other). When several causes give categories, the first in Cipolle’s order of assessment wins (indication → effectiveness → safety → adherence). With no category from the causes, the problem’s own category is used.`,
  '',
  approved ? '## Choices the owner confirmed (⚑)' : '## Choices for you to confirm (⚑)',
  '',
  ...decide.map(([code, r]) => `- **${code}** ${esc(PCNE_CODE.get(code)!.label.en)} → **${boxLabel(r.box)}**. ${r.why ?? ''}`),
  '',
  '## Problems',
  '',
  '| Code | PCNE V9.1 wording | Department form box | Cipolle category | Why |',
  '|---|---|---|---|---|',
  ...rows(PCNE_PROBLEMS),
  '',
  '## Causes',
  '',
  '| Code | PCNE V9.1 wording | Department form box | Cipolle category | Why |',
  '|---|---|---|---|---|',
  ...rows(PCNE_CAUSES),
  '',
  '## Worked examples (computed by the app’s own functions)',
  '',
  '| Problem | Causes | Form boxes ticked | Written under “other” | Cipolle category (decided by) |',
  '|---|---|---|---|---|',
  ...EXAMPLES.map(([p, cs]) => {
    const f = formBoxesFor(p, cs);
    const c = cipolleFor(p, cs);
    return `| ${p} | ${cs.join(', ') || '—'} | ${f.boxes.map(boxLabel).join(', ')} | ${esc(f.otherText.join('; ')) || '—'} | ${c.category ? `${c.category.label.en} (${c.from})` : 'no equivalent'} |`;
  }),
  '',
];

writeFileSync(OUT, lines.join('\n'));
process.stdout.write(`wrote ${OUT}\n`);
